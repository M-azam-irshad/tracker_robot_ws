#!/usr/bin/env python3
"""Regenerates worlds/*.sdf (deterministic, seeded).   usage: python3 generate_worlds.py
World name is 'sar_world' in every file so the bridge topic names are identical.

Frame: robot spawns at (0,0) facing +X. Gas-source positions below MUST match
config/sensors.yaml (gas_simulator plume_x / plume_y)."""
import math
import os
import random

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'worlds')
WORLD = 'sar_world'


def f(v):
    return f'{v:.4f}'


def pose(x=0, y=0, z=0, r=0, p=0, yw=0):
    return f'<pose>{f(x)} {f(y)} {f(z)} {f(r)} {f(p)} {f(yw)}</pose>'


def rgba(c, a=1.0):
    return f'{c[0]} {c[1]} {c[2]} {a}'


def mat(c, a=1.0):
    return f'<material><ambient>{rgba(c, a)}</ambient><diffuse>{rgba(c, a)}</diffuse></material>'


FRICTION = '<surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface>'


def box(name, x, y, z, sx, sy, sz, r=0, p=0, yw=0, color=(0.5, 0.5, 0.5)):
    g = f'<box><size>{f(sx)} {f(sy)} {f(sz)}</size></box>'
    return (f'<model name="{name}"><static>true</static>{pose(x, y, z, r, p, yw)}'
            f'<link name="link"><collision name="c"><geometry>{g}</geometry>{FRICTION}</collision>'
            f'<visual name="v"><geometry>{g}</geometry>{mat(color)}</visual></link></model>')


def cyl(name, x, y, z, rad, length, r=0, p=0, yw=0, color=(0.5, 0.5, 0.5)):
    g = f'<cylinder><radius>{f(rad)}</radius><length>{f(length)}</length></cylinder>'
    return (f'<model name="{name}"><static>true</static>{pose(x, y, z, r, p, yw)}'
            f'<link name="link"><collision name="c"><geometry>{g}</geometry>{FRICTION}</collision>'
            f'<visual name="v"><geometry>{g}</geometry>{mat(color)}</visual></link></model>')


def ghost_sphere(name, x, y, z, rad, color):
    """Visual-only translucent sphere (shows ground-truth gas plume centre)."""
    g = f'<sphere><radius>{f(rad)}</radius></sphere>'
    return (f'<model name="{name}"><static>true</static>{pose(x, y, z)}'
            f'<link name="link"><visual name="v"><geometry>{g}</geometry>{mat(color, 0.25)}'
            f'<cast_shadows>false</cast_shadows></visual></link></model>')


def victim(name, x, y, yaw):
    """Simple lying humanoid: torso, head, legs (static, collidable)."""
    parts = [
        ('torso', (0.0, 0.0, 0.10), f'<box><size>0.50 0.32 0.18</size></box>', (0.95, 0.45, 0.05)),
        ('head', (0.34, 0.0, 0.11), '<sphere><radius>0.10</radius></sphere>', (0.85, 0.65, 0.5)),
        ('legs', (-0.45, 0.0, 0.07), '<box><size>0.50 0.22 0.12</size></box>', (0.15, 0.2, 0.45)),
    ]
    links = ''
    for n, (px, py, pz), g, c in parts:
        links += (f'<collision name="{n}_c">{pose(px, py, pz)}<geometry>{g}</geometry></collision>'
                  f'<visual name="{n}_v">{pose(px, py, pz)}<geometry>{g}</geometry>{mat(c)}</visual>')
    return (f'<model name="{name}"><static>true</static>{pose(x, y, 0, 0, 0, yaw)}'
            f'<link name="link">{links}</link></model>')


def ground():
    g = '<plane><normal>0 0 1</normal><size>200 200</size></plane>'
    return (f'<model name="ground_plane"><static>true</static><link name="link">'
            f'<collision name="c"><geometry>{g}</geometry>{FRICTION}</collision>'
            f'<visual name="v"><geometry>{g}</geometry>{mat((0.35, 0.33, 0.30))}</visual>'
            f'</link></model>')


def point_light(name, x, y, z, diffuse='0.9 0.8 0.6 1', rng=9):
    return (f'<light type="point" name="{name}">{pose(x, y, z)}<cast_shadows>false</cast_shadows>'
            f'<diffuse>{diffuse}</diffuse><specular>0.1 0.1 0.1 1</specular>'
            f'<attenuation><range>{rng}</range><constant>0.4</constant><linear>0.08</linear>'
            f'<quadratic>0.01</quadratic></attenuation></light>')


SUN = ('<light type="directional" name="sun"><cast_shadows>true</cast_shadows>'
       '<pose>0 0 10 0 0 0</pose><diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular>'
       '<direction>-0.5 0.1 -0.9</direction></light>')


def world(contents, ambient='0.6 0.6 0.6 1', background='0.5 0.6 0.7 1'):
    return f'''<?xml version="1.0" ?>
<!-- AUTO-GENERATED by scripts/generate_worlds.py -->
<sdf version="1.9">
  <world name="{WORLD}">
    <physics name="sim_physics" type="ignored">
      <max_step_size>0.003</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <gravity>0 0 -9.81</gravity>
    <scene>
      <ambient>{ambient}</ambient>
      <background>{background}</background>
      <shadows>true</shadows>
    </scene>
{contents}
  </world>
</sdf>
'''


def rubble(rng, prefix, x0, x1, y0, y1, n, smin=0.04, smax=0.09):
    """Rocks sized for THIS rover: roller radius 8.45 cm -> protrusion kept <= ~8 cm."""
    out = []
    for i in range(n):
        sx, sy, sz = (rng.uniform(smin, smax) for _ in range(3))
        x, y = rng.uniform(x0, x1), rng.uniform(y0, y1)
        r, p, yw = rng.uniform(-0.3, 0.3), rng.uniform(-0.3, 0.3), rng.uniform(0, math.pi)
        z = rng.uniform(0.25, 0.4) * sz
        shade = rng.uniform(0.25, 0.5)
        out.append(box(f'{prefix}_{i}', x, y, z, sx, sy, sz, r, p, yw, (shade, shade * 0.95, shade * 0.9)))
    return out


def make_empty():
    return world('\n'.join([SUN, ground()]))


def make_test_env():
    rng = random.Random(7)
    c = [SUN, ground()]
    th = math.radians(15)
    L = 2.0
    # 15 deg ramp rising along +X, followed by a plateau
    c.append(box('ramp_15deg', 2.0 + L / 2 * math.cos(th), 0, L / 2 * math.sin(th) - 0.02,
                 L, 1.2, 0.05, 0, -th, 0, (0.55, 0.5, 0.4)))
    top = L * math.sin(th)
    c.append(box('plateau', 2.0 + L * math.cos(th) + 0.75, 0, top / 2 - 0.02, 1.5, 1.2, top,
                 color=(0.5, 0.45, 0.38)))
    # stairs (5 x 6 cm risers) on the -Y side
    for i in range(5):
        c.append(box(f'stair_{i}', 2.0 + i * 0.25 + 0.125, -3.0, 0.03 * (i + 1),
                     0.25, 1.2, 0.06 * (i + 1), color=(0.6, 0.6, 0.62)))
    # speed bumps (cylinders lying along Y)
    for i in range(4):
        c.append(cyl(f'bump_{i}', 2.5 + i * 0.8, 3.0, 0.0, 0.05, 1.6, r=math.pi / 2,
                     color=(0.9, 0.7, 0.1)))
    # rubble field
    c += rubble(rng, 'rubble', 7.0, 11.0, -2.5, 2.5, 80)
    # wall at end
    c.append(box('end_wall', 13.0, 0, 0.75, 0.2, 8.0, 1.5, color=(0.4, 0.4, 0.45)))
    return world('\n'.join(c))


# --- search & rescue world -------------------------------------------------
GAS_SOURCES = [  # name, x, y, sigma, rgb   (keep in sync with config/sensors.yaml)
    ('gas_co', 7.0, 0.5, 2.0, (1.0, 0.5, 0.0)),
    ('gas_ch4', 9.0, 5.5, 1.8, (1.0, 0.1, 0.1)),
    ('gas_h2s', 14.0, -0.8, 1.5, (0.8, 0.9, 0.1)),
]
VICTIMS = [('victim_1', 6.6, -1.0, 0.4), ('victim_2', 9.2, 5.0, -1.2), ('victim_3', 14.6, 0.8, 2.6)]


def make_sar():
    rng = random.Random(42)
    c = [ground()]
    wall_c = (0.28, 0.24, 0.20)
    H, T = 2.5, 0.2
    hw = 1.5  # corridor half width
    x_start, x_end = -1.5, 16.0
    bx, bw = 9.0, 1.25     # side branch centre x, half width
    y_end = 7.5
    # main corridor, south wall (full)
    c.append(box('wall_s', (x_start + x_end) / 2, -hw - T / 2, H / 2, x_end - x_start, T, H, color=wall_c))
    # north wall with opening for the side branch
    l1 = (bx - bw) - x_start
    l2 = x_end - (bx + bw)
    c.append(box('wall_n1', x_start + l1 / 2, hw + T / 2, H / 2, l1, T, H, color=wall_c))
    c.append(box('wall_n2', bx + bw + l2 / 2, hw + T / 2, H / 2, l2, T, H, color=wall_c))
    # end walls
    c.append(box('wall_end', x_end + T / 2, 0, H / 2, T, 2 * hw + 2 * T, H, color=wall_c))
    c.append(box('wall_back', x_start - T / 2, 0, H / 2, T, 2 * hw + 2 * T, H, color=wall_c))
    # side branch
    bl = y_end - hw
    c.append(box('branch_w', bx - bw - T / 2, hw + bl / 2, H / 2, T, bl, H, color=wall_c))
    c.append(box('branch_e', bx + bw + T / 2, hw + bl / 2, H / 2, T, bl, H, color=wall_c))
    c.append(box('branch_end', bx, y_end + T / 2, H / 2, 2 * bw + 2 * T, T, H, color=wall_c))
    # fallen ceiling slabs (tilted, partially blocking)
    c.append(box('slab_1', 4.2, -0.9, 0.03, 0.9, 0.7, 0.05, 0, -0.08, 0.3, (0.4, 0.4, 0.4)))
    c.append(box('slab_2', 11.5, 0.8, 0.03, 0.9, 0.8, 0.05, 0.07, 0, -0.5, (0.4, 0.4, 0.4)))
    c.append(box('slab_3', 9.0, 3.8, 0.03, 0.9, 0.8, 0.05, 0, 0.08, 1.0, (0.4, 0.4, 0.4)))
    # rubble zones (spawn area x<2.5 kept clear)
    c += rubble(rng, 'rub_a', 3.0, 5.5, -1.3, 1.3, 35)
    c += rubble(rng, 'rub_b', 6.0, 8.0, -1.3, 1.3, 35)
    c += rubble(rng, 'rub_c', 10.5, 13.0, -1.3, 1.3, 35)
    c += rubble(rng, 'rub_d', 8.0, 10.0, 2.0, 6.5, 40)
    # victims
    for n, x, y, yw in VICTIMS:
        c.append(victim(n, x, y, yw))
    # translucent gas plume centres (ground truth, visual only)
    for n, x, y, s, col in GAS_SOURCES:
        c.append(ghost_sphere(n, x, y, 0.5, s * 0.5, col))
    # dim lighting
    for i, (lx, ly) in enumerate([(2, 0), (6, 0), (10, 0), (14, 0), (9, 4)]):
        c.append(point_light(f'lamp_{i}', lx, ly, 2.2))
    return world('\n'.join(c), ambient='0.18 0.18 0.2 1', background='0.02 0.02 0.03 1')


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for fn, fnc in [('empty.sdf', make_empty), ('test_environment.sdf', make_test_env),
                    ('search_and_rescue_world.sdf', make_sar)]:
        with open(os.path.join(OUT, fn), 'w') as fh:
            fh.write(fnc())
        print('wrote', fn)
