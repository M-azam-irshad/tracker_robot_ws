#!/usr/bin/env python3
"""Procedurally generates light-weight visual meshes (binary STL, metres) from the dimensions
extracted from the SolidWorks STEP files (track__updated.step etc.).
Replace the files in meshes/visual with real decimated CAD exports at any time - keep the same
file names and the same local frames (documented below).

Frames: track_belt.stl  origin = sprocket axle centre, profile in the X-Z plane (x forward), width along Y.
        roller.stl / sprocket.stl origin = axle centre, spin axis = Y.
Run:    python3 generate_meshes.py   (writes ../meshes/visual/...)"""
import math
import os
import struct

import numpy as np

# ---- dimensions from STEP (mm -> m) ------------------------------------------------------
R_SPROCKET_PATH = 0.095          # track path radius around sprocket
R_ROLLER_PATH = 0.0675           # track path radius around rollers
ROLLER_X = 0.1531                # roller axle x offset from sprocket axle (+/-)
ROLLER_DROP = 0.1035             # roller axle below sprocket axle
BELT_T = 0.006                   # rubber band thickness
LUG_H = 0.011                    # lug height above the band -> outer radius = path + 17 mm (STEP)
TRACK_W = 0.115                  # table: 11.5 cm
LUG_PITCH = 0.0254
LUG_T = 0.009

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'meshes', 'visual')


# ---- tiny mesh helpers -------------------------------------------------------------------
class Mesh:
    def __init__(self):
        self.tris = []

    def tri(self, a, b, c, expect=None):
        a, b, c = map(np.asarray, (a, b, c))
        n = np.cross(b - a, c - a)
        if expect is not None and np.dot(n, expect) < 0:
            b, c = c, b
        self.tris.append((a, b, c))

    def quad(self, a, b, c, d, expect=None):
        self.tri(a, b, c, expect)
        self.tri(a, c, d, expect)

    def convex(self, verts_faces):
        """add a convex solid; orient every triangle outward using the centroid"""
        verts, faces = verts_faces
        cen = np.mean(verts, axis=0)
        for f in faces:
            a, b, c = (np.asarray(verts[i]) for i in f)
            out = (a + b + c) / 3.0 - cen
            self.tri(a, b, c, out)

    def save(self, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'wb') as fh:
            fh.write(b'generated by generate_meshes.py'.ljust(80, b' '))
            fh.write(struct.pack('<I', len(self.tris)))
            for a, b, c in self.tris:
                n = np.cross(b - a, c - a)
                n = n / (np.linalg.norm(n) + 1e-12)
                fh.write(struct.pack('<12fH', *n, *a, *b, *c, 0))
        print('wrote', os.path.relpath(path, HERE), len(self.tris), 'triangles')


def box_vf(center, ax_t, ax_n, ax_y, size):
    """oriented box; ax_* unit vectors, size=(lt, ln, ly)"""
    c = np.asarray(center)
    v = []
    for st in (-1, 1):
        for sn in (-1, 1):
            for sy in (-1, 1):
                v.append(c + st * size[0] / 2 * ax_t + sn * size[1] / 2 * ax_n + sy * size[2] / 2 * ax_y)
    f = [(0, 1, 3), (0, 3, 2), (4, 6, 7), (4, 7, 5), (0, 4, 5), (0, 5, 1),
         (2, 3, 7), (2, 7, 6), (0, 2, 6), (0, 6, 4), (1, 5, 7), (1, 7, 3)]
    return v, f


def cyl_vf(center, radius, length, n=32, y_axis=True):
    c = np.asarray(center)
    v, f = [], []
    for sy in (-1, 1):
        for i in range(n):
            a = 2 * math.pi * i / n
            v.append(c + np.array([radius * math.cos(a), sy * length / 2, radius * math.sin(a)]))
    v.append(c + np.array([0, -length / 2, 0]))
    v.append(c + np.array([0, length / 2, 0]))
    cm, cp = 2 * n, 2 * n + 1
    for i in range(n):
        j = (i + 1) % n
        f += [(i, j, n + j), (i, n + j, n + i), (cm, j, i), (cp, n + i, n + j)]
    return v, f


# ---- track path ----------------------------------------------------------------------------
CIRCLES = [  # CCW hull order: front roller -> sprocket -> rear roller
    (np.array([ROLLER_X, -ROLLER_DROP]), R_ROLLER_PATH),
    (np.array([0.0, 0.0]), R_SPROCKET_PATH),
    (np.array([-ROLLER_X, -ROLLER_DROP]), R_ROLLER_PATH),
]


def tangent_normal(A, rA, B, rB):
    """outward unit normal of the external tangent line when travelling A->B counter-clockwise"""
    d = np.linalg.norm(B - A)
    u = (B - A) / d
    perp = np.array([u[1], -u[0]])               # u rotated -90 deg (right-hand side)
    k = (rA - rB) / d
    return k * u + math.sqrt(max(0.0, 1 - k * k)) * perp


def build_path(step_deg=4.0):
    """returns list of (point, outward normal) closed loop and the 3 tangent segments"""
    n_c = len(CIRCLES)
    norms = [tangent_normal(CIRCLES[i][0], CIRCLES[i][1], CIRCLES[(i + 1) % n_c][0], CIRCLES[(i + 1) % n_c][1])
             for i in range(n_c)]
    segs = []
    for i in range(n_c):
        A, rA = CIRCLES[i]
        B, rB = CIRCLES[(i + 1) % n_c]
        segs.append((A + rA * norms[i], B + rB * norms[i], norms[i]))
    pts = []
    for i in range(n_c):
        C, r = CIRCLES[i]
        n_in = norms[i - 1]
        n_out = norms[i]
        a0 = math.atan2(n_in[1], n_in[0])
        a1 = math.atan2(n_out[1], n_out[0])
        while a1 < a0:
            a1 += 2 * math.pi
        k = max(2, int(math.degrees(a1 - a0) / step_deg))
        for j in range(k + 1):
            a = a0 + (a1 - a0) * j / k
            nn = np.array([math.cos(a), math.sin(a)])
            pts.append((C + r * nn, nn))
    return pts, segs


def to3(p2, y):
    return np.array([p2[0], y, p2[1]])


def make_belt():
    pts, _ = build_path()
    m = Mesh()
    hw = TRACK_W / 2
    Y = np.array([0, 1.0, 0])
    N = len(pts)
    for i in range(N):
        (p0, n0), (p1, n1) = pts[i], pts[(i + 1) % N]
        for (a, b, na, nb, e) in ((p0, p1, n0, n1, 1), ):
            o0, o1 = a + BELT_T * na, b + BELT_T * nb
            nm = to3((na + nb) / 2, 0) * 0 + np.array([(na + nb)[0] / 2, 0, (na + nb)[1] / 2])
            m.quad(to3(o0, -hw), to3(o1, -hw), to3(o1, hw), to3(o0, hw), nm)             # outer
            m.quad(to3(a, -hw), to3(b, -hw), to3(b, hw), to3(a, hw), -nm)                # inner
            for sy in (-1, 1):                                                           # sides
                m.quad(to3(a, sy * hw), to3(b, sy * hw), to3(o1, sy * hw), to3(o0, sy * hw), sy * Y)
    # lugs (cross cleats) at constant arc-length pitch
    seglen = [np.linalg.norm(pts[(i + 1) % N][0] - pts[i][0]) for i in range(N)]
    total = sum(seglen)
    count = int(total / LUG_PITCH)
    for k in range(count):
        s = k * total / count
        i = 0
        while s > seglen[i]:
            s -= seglen[i]
            i += 1
        (p0, n0), (p1, n1) = pts[i], pts[(i + 1) % N]
        t = s / seglen[i]
        p = p0 + (p1 - p0) * t
        n = n0 + (n1 - n0) * t
        n /= np.linalg.norm(n)
        tang = np.array([n[1], -n[0]])
        center = p + n * (BELT_T + LUG_H) / 2 - n * 0.0
        h = BELT_T + LUG_H
        m.convex(box_vf(to3(center, 0), to3(tang, 0) * 0 + np.array([tang[0], 0, tang[1]]),
                        np.array([n[0], 0, n[1]]), np.array([0, 1.0, 0]), (LUG_T, h, TRACK_W)))
    return m


